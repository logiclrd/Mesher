#pragma once

#include "mesher/repair_cap_spatial.hpp"
#include "mesher/repair_cap.hpp"

#include <array>
#include <cstddef>
#include <cstdint>
#include <vector>

namespace mesher {

// M23B: source-boundary coordinates are cap-facing (reverse of R03's
// survivor-facing contour). The first and second arrays need not have
// equal vertex counts, except for a *self-reflected* pair.
struct UnifiedZipperRim {
    std::vector<VertexId> ids;
    std::vector<Vec3> positions;
    std::vector<Vec3> outgoingNormals;
};

// This patch is entirely PRIVATE and uses patch-local vertex indexes.
// For positions[i] where i<boundaryIds.size(), boundaryIds[i]!=0 means
// an original R03 vertex; 0 means a newly inserted bridge vertex.
// All positions past boundaryIds.size() are generated by the AFM cap.
// The first bridgeFaceCount faces are finite bridge seed triangles.
struct UnifiedZipperFrontPatch {
    std::vector<Vec3> positions;
    std::vector<VertexId> boundaryIds;
    std::vector<std::array<std::uint32_t,3>> faces;
    std::size_t bridgeFaceCount{};
    std::size_t bridgeVertexCount{};
    std::size_t poissonIterations{};
    double poissonResidual{};
    double minimumSeedQuality{1};
    bool selfReflected{};
};

// Uses the SAME existing advancing-front spatial cap generator after
// constructing a finite-width, positively embedded seed between the rims.
// The generator never publishes or welds source vertex identities.
// All returned geometry still requires M04 global source-backed validation.
UnifiedZipperFrontPatch buildUnifiedZipperFront(
    const UnifiedZipperRim& first,
    const UnifiedZipperRim& second,
    bool selfReflected,
    const SpatialCapSettings& settings,
    const SpatialCapPlacementAdjustment* adjustment=nullptr);
}
