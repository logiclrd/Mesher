// A mirror-invariant alternative to the hub fan: each original half-rim
// connects to a true x=0 polyline using its own projected (y,z) coordinates.
// The reflected half is generated by inverse-winding faces, NEVER by
// independently choosing triangulation diagonals or welding rim identities.
SpatialCapPatch mirroredRibbon(
    const std::vector<Vec3>& rim,
    const std::vector<std::size_t>& partner,
    const SpatialCapSettings& limits) {
    const auto n=rim.size();
    std::vector<std::size_t> seams;
    for(std::size_t i=0;i<n;++i)
        if(rim[i].x==0)seams.push_back(i);
    if(seams.size()!=2)
        throw std::logic_error("R06-M06C mirrored ribbon needs two real seam endpoints");

    std::vector<std::size_t> side;
    for(std::size_t i=seams[0];;i=(i+1)%n) {
        side.push_back(i);
        if(i==seams[1])break;
    }
    if(side.size()<3||side.size()>n-1)
        throw std::logic_error("R06-M06C mirrored ribbon has malformed half-rim");
    const auto sign=rim[side[1]].x<0?-1:1;
    if(!std::all_of(side.begin()+1,side.end()-1,
                    [&](std::size_t i){return rim[i].x*sign>0;}))
        throw std::logic_error("R06-M06C mirrored ribbon half-rim crosses seam");
    if(side.size()*2!=n+2)
        throw std::logic_error("R06-M06C mirrored ribbon rim orbit count");
    for(std::size_t k=0;k<side.size();++k)
        if(partner[side[k]]!=side[k]&&
           rim[partner[side[k]]].x*sign>=0)
            throw std::logic_error("R06-M06C mirrored ribbon reflected orbit lies on wrong half");

    SpatialCapPatch patch;
    patch.boundaryCount=n;
    patch.usedMirroredRibbonFallback=true;
    patch.positions=rim;
    std::vector<std::uint32_t> seamIds;
    seamIds.reserve(side.size());
    seamIds.push_back(static_cast<std::uint32_t>(side.front()));
    for(std::size_t k=1;k+1<side.size();++k) {
        const auto p=rim[side[k]];
        for(const auto seamId:seamIds) {
            const auto q=patch.positions[seamId];
            if(q.y==p.y&&q.z==p.z)
                throw std::logic_error("R06-M06C mirrored ribbon duplicates a seam position");
        }
        if(patch.positions.size()-n>=limits.maxInteriorVertices)
            throw std::length_error("R06-M06C mirrored ribbon interior budget");
        seamIds.push_back(static_cast<std::uint32_t>(patch.positions.size()));
        patch.positions.push_back({0,p.y,p.z});
    }
    seamIds.push_back(static_cast<std::uint32_t>(side.back()));
    // Avoid ambiguous self-overlapping centerline even when vertices differ.
    for(std::size_t k=0;k<seamIds.size();++k)
        for(std::size_t j=k+1;j<seamIds.size();++j) {
            const auto a=patch.positions[seamIds[k]];
            const auto b=patch.positions[seamIds[j]];
            if(a.y==b.y&&a.z==b.z)
                throw std::logic_error("R06-M06C mirrored ribbon collapses distinct seam vertices");
        }

    const auto addPaired=[&](std::array<std::uint32_t,3> t) {
        if(patch.faces.size()+2>limits.maxFaces)
            throw std::length_error("R06-M06C mirrored ribbon face budget");
        patch.faces.push_back(t);
        const auto reflectId=[&](std::uint32_t id)->std::uint32_t {
            return id<n?static_cast<std::uint32_t>(partner[id]):id;
        };
        patch.faces.push_back({reflectId(t[0]),reflectId(t[2]),
                               reflectId(t[1])});
    };
    for(std::size_t k=0;k+1<side.size();++k) {
        const auto a=static_cast<std::uint32_t>(side[k]);
        const auto b=static_cast<std::uint32_t>(side[k+1]);
        const auto c=seamIds[k],d=seamIds[k+1];
        if(a!=c)addPaired({a,b,c});
        if(b!=d)addPaired({b,d,c});
    }
    if(patch.faces.size()!=2*n-4)
        throw std::logic_error("R06-M06C mirrored ribbon missing a half-strip face");
    return patch;
}

// M22A: the fixed-rim Poisson stage depends on indexed connectivity and
// explicit interior guidance, NEVER on a ring vertex ordinal or a hub.
void solveSpatialCapFixedRimPoisson(
    SpatialCapPatch& patch,
    const std::vector<Vec3>& interiorGuidance,
    const SpatialCapSettings& limits,
    const std::vector<std::size_t>& mirrorPartners) {
    const auto n=patch.boundaryCount;
    if(n<3||n>limits.maxBoundaryVertices||
       patch.positions.size()<n||
       patch.positions.size()-n>limits.maxInteriorVertices||
       patch.faces.empty()||patch.faces.size()>limits.maxFaces||
       !limits.maxPoissonIterations||
       !std::isfinite(limits.poissonTolerance)||limits.poissonTolerance<=0||
       !std::isfinite(limits.normalGuidance)||
       limits.normalGuidance<0||limits.normalGuidance>.5||
       !std::isfinite(limits.placementAnchorWeight)||
       limits.placementAnchorWeight<0||
       limits.placementAnchorWeight>4||
       interiorGuidance.size()!=patch.positions.size()-n)
        throw std::invalid_argument("R06-M22A invalid generic Poisson input or finite bounds");

    for(const auto p:patch.positions)
        if(!finite(p))throw std::logic_error("R06-M22A nonfinite patch position");
    for(const auto direction:interiorGuidance)
        if(!finite(direction))
            throw std::logic_error("R06-M22A nonfinite interior guidance");
    std::vector<double> originalEdges;
    originalEdges.reserve(n);
    for(std::size_t i=0;i<n;++i)
        originalEdges.push_back(length(
            patch.positions[(i+1)%n]-patch.positions[i]));
    std::sort(originalEdges.begin(),originalEdges.end());
    const auto h=originalEdges[n/2];
    if(!(h>1e-12)||!std::isfinite(h))
        throw std::logic_error("R06-M22A degenerate fixed boundary scale");

    const auto reflect=[](Vec3 p) {return Vec3{-p.x,p.y,p.z};};
    if(limits.requireMirrorPlane) {
        if(mirrorPartners.size()!=patch.positions.size())
            throw std::logic_error("R06-M22A missing exact mirror partner map");
        for(std::size_t i=0;i<patch.positions.size();++i) {
            const auto j=mirrorPartners[i];
            if(j>=patch.positions.size()||mirrorPartners[j]!=i||
               ((i<n)!=(j<n)))
                throw std::logic_error("R06-M22A invalid reflected vertex orbit");
            const auto p=patch.positions[i],q=patch.positions[j];
            if(q.x!=-p.x||q.y!=p.y||q.z!=p.z||
               (j==i&&p.x!=0))
                throw std::logic_error("R06-M22A inaccurate reflected vertex positions");
            if(i>=n) {
                const auto a=interiorGuidance[i-n],b=interiorGuidance[j-n];
                if(b.x!=-a.x||b.y!=a.y||b.z!=a.z)
                    throw std::logic_error("R06-M22A non-reflected Poisson guidance");
            }
        }
    }else if(!mirrorPartners.empty()) {
        throw std::invalid_argument("R06-M22A unexpected asymmetric mirror mapping");
    }

    std::vector<std::set<std::uint32_t>> adjacent(patch.positions.size());
    for(const auto& face:patch.faces) {
        for(unsigned k=0;k<3;++k)
            if(face[k]>=patch.positions.size()||
               face[k]==face[(k+1)%3])
                throw std::logic_error("R06-M22A malformed patch face");
        for(unsigned k=0;k<3;++k) {
            const auto a=face[k],b=face[(k+1)%3];
            adjacent[a].insert(b);
            adjacent[b].insert(a);
        }
    }
    for(std::size_t i=n;i<patch.positions.size();++i)
        if(adjacent[i].empty())
            throw std::logic_error("R06-M22A orphan interior Poisson vertex");

    // Compute in a private copy; on any refusal the original caller's
    // patch remains bit-identical (including solver metadata).
    auto candidate=patch;
    const auto anchors=patch.positions;
    const auto anchorWeight=limits.placementAnchorWeight;
    const auto sourceAt=[&](std::size_t i) {
        const auto direction=interiorGuidance[i-n];
        const auto degree=static_cast<double>(adjacent[i].size());
        return direction*(limits.normalGuidance*h*degree);
    };
    bool converged=false;
    const auto tolerance=limits.poissonTolerance*h;
    for(std::size_t iteration=0;iteration<limits.maxPoissonIterations;++iteration) {
        double residual=0;
        if(limits.requireMirrorPlane) {
            // Jacobi updates and exact pair projection commute with reflection.
            auto next=candidate.positions;
            for(std::size_t i=n;i<candidate.positions.size();++i) {
                Vec3 rhs=sourceAt(i);
                for(const auto neighbor:adjacent[i])
                    rhs=rhs+candidate.positions[neighbor];
                if(anchorWeight>0)rhs=rhs+anchors[i]*anchorWeight;
                next[i]=rhs/(static_cast<double>(adjacent[i].size())+
                             anchorWeight);
                if(!finite(next[i]))
                    throw std::logic_error(
                        "R06-M22A mirrored Poisson nonfinite interior vertex");
            }
            for(std::size_t i=n;i<next.size();++i) {
                const auto j=mirrorPartners[i];
                if(j<i)continue;
                if(j==i) {
                    next[i].x=0;
                }else {
                    const auto mean=(next[i]+reflect(next[j]))*.5;
                    next[i]=mean;
                    next[j]=reflect(mean);
                }
            }
            for(std::size_t i=n;i<next.size();++i)
                residual=std::max(residual,
                    length(next[i]-candidate.positions[i]));
            candidate.positions=std::move(next);
        }else {
            for(std::size_t i=n;i<candidate.positions.size();++i) {
                Vec3 rhs=sourceAt(i);
                for(const auto neighbor:adjacent[i])
                    rhs=rhs+candidate.positions[neighbor];
                if(anchorWeight>0)rhs=rhs+anchors[i]*anchorWeight;
                const auto updated=rhs/
                    (static_cast<double>(adjacent[i].size())+anchorWeight);
                if(!finite(updated))
                    throw std::logic_error(
                        "R06-M22A Poisson produced nonfinite interior vertex");
                residual=std::max(residual,length(updated-candidate.positions[i]));
                candidate.positions[i]=updated;
            }
        }
        candidate.poissonIterations=iteration+1;
        candidate.poissonResidual=residual;
        if(residual<=tolerance){converged=true;break;}
    }
    if(!converged)
        throw std::logic_error("R06-M22A Poisson did not meet finite residual bound");
    for(std::size_t i=0;i<n;++i)
        if(candidate.positions[i].x!=patch.positions[i].x||
           candidate.positions[i].y!=patch.positions[i].y||
           candidate.positions[i].z!=patch.positions[i].z)
            throw std::logic_error("R06-M22A fixed R03 rim moved");
    patch=std::move(candidate);
}

// M22B: ordinary advancing-front construction. This produces the SAME
// SpatialCapPatch interface consumed by the existing source-backed M04 stage.
// All edits are local copies. The only mirror-specific rules are paired
// operations, a seam-vertex two-triangle turn, and no cross-plane edge.
namespace {
struct AdaptiveFrontState {
    SpatialCapPatch patch;
    std::vector<std::uint32_t> front;
    std::vector<std::size_t> twins;
    std::vector<Vec3> guides; // indexed by all positions (rim included)
    std::vector<std::uint8_t> originSides; // 0=unattributed ordinary cap
};

SpatialCapPatch constructAdaptiveFront(
    const std::vector<Vec3>& rim,
    const std::vector<Vec3>& normals,
    const std::vector<std::size_t>& boundaryTwins,
    const SpatialCapSettings& limits,
    const SpatialCapPlacementAdjustment* placementAdjustment,
    const std::vector<std::uint8_t>* rimSides) {
    const auto n=rim.size();
    if(n<3||n>limits.maxBoundaryVertices||
       !(limits.nearSeamSnapFraction>=0&&
         limits.nearSeamSnapFraction<=.5&&
         std::isfinite(limits.nearSeamSnapFraction)))
        throw std::invalid_argument("R06-M22B invalid advancing-front limits");
    AdaptiveFrontState state;
    state.patch.boundaryCount=n;
    state.patch.usedAdaptiveFront=true;
    state.patch.positions=rim;
    state.front.reserve(n+limits.maxInteriorVertices);
    state.guides.reserve(n+limits.maxInteriorVertices);
    state.twins.reserve(n+limits.maxInteriorVertices);
    state.originSides.reserve(n+limits.maxInteriorVertices);
    if(rimSides&&rimSides->size()!=n)
        throw std::invalid_argument("R06-M23B invalid seed-front side ancestry");
    Vec3 area{};
    for(std::size_t i=0;i<n;++i) {
        const auto j=(i+1)%n;
        state.front.push_back(static_cast<std::uint32_t>(i));
        area=area+cross(rim[i],rim[j]);
        auto g=normals.empty()?Vec3{}:normals[i];
        if(!finite(g))throw std::logic_error("R06-M22B nonfinite rim guidance");
        const auto m=length(g);
        state.guides.push_back(m>1e-12?g/m:Vec3{});
        state.twins.push_back(limits.requireMirrorPlane?boundaryTwins[i]:i);
        state.originSides.push_back(rimSides?rimSides->at(i):0);
    }
    const auto reflect=[](Vec3 p){return Vec3{-p.x,p.y,p.z};};
    const auto rimScale=[&]() {
        std::vector<double> lengths;
        lengths.reserve(n);
        for(std::size_t i=0;i<n;++i)
            lengths.push_back(length(rim[(i+1)%n]-rim[i]));
        std::sort(lengths.begin(),lengths.end());
        return lengths[n/2];
    }();
    if(!(rimScale>1e-12&&std::isfinite(rimScale)))
        throw std::logic_error("R06-M22B degenerate front scale");
    const auto normal=length(area)>1e-12?normalized(area):Vec3{0,0,1};
    const auto samePoint=[](Vec3 a,Vec3 b) {
        return a.x==b.x&&a.y==b.y&&a.z==b.z;
    };
    const auto addFace=[&](AdaptiveFrontState& s,
                          std::uint32_t a,std::uint32_t b,std::uint32_t d) {
        s.patch.faces.push_back({a,b,d});
    };
    std::size_t tests=0;
    std::size_t attempts=0;
    const auto legal=[&](const AdaptiveFrontState& s) {
        if(s.patch.faces.size()>limits.maxFaces||
           s.patch.positions.size()-n>limits.maxInteriorVertices||
           s.front.size()>limits.maxFaces+2)
            return false;
        std::set<std::uint32_t> unique;
        for(const auto id:s.front) {
            if(id>=s.patch.positions.size()||!unique.insert(id).second)
                return false;
        }
        if(limits.requireMirrorPlane) {
            if(s.twins.size()!=s.patch.positions.size())return false;
            for(std::size_t i=0;i<s.twins.size();++i) {
                const auto j=s.twins[i];
                if(j>=s.twins.size()||s.twins[j]!=i||
                   !samePoint(s.patch.positions[j],
                              reflect(s.patch.positions[i])))
                    return false;
            }
        }
        // No front edge may straddle X=0 without a real seam vertex.
        for(std::size_t i=0;i<s.front.size();++i) {
            const auto a=s.patch.positions[s.front[i]];
            const auto b=s.patch.positions[s.front[(i+1)%s.front.size()]];
            if(limits.requireMirrorPlane&&a.x*b.x<0)return false;
        }
        for(const auto& face:s.patch.faces) {
            if(face[0]>=s.patch.positions.size()||
               face[1]>=s.patch.positions.size()||
               face[2]>=s.patch.positions.size())
                return false;
            const auto a=s.patch.positions[face[0]];
            const auto b=s.patch.positions[face[1]];
            const auto d=s.patch.positions[face[2]];
            if(limits.requireMirrorPlane&&
               std::min({a.x,b.x,d.x})<0&&
               std::max({a.x,b.x,d.x})>0)return false;
            if(!(quality(a,b,d)>1e-8))return false;
        }
        // Bounded contact checks on generated faces, including intersections
        // caused by otherwise plausible but folded advancing-front turns.
        for(std::size_t i=0;i<s.patch.faces.size();++i)
        for(std::size_t j=i+1;j<s.patch.faces.size();++j) {
            // Previous committed faces were already checked. Only contact
            // pairs involving this candidate's new faces need rechecking.
            if(i<state.patch.faces.size()&&
               j<state.patch.faces.size())continue;
            std::array<Vec3,3> p{},q{};
            std::array<VertexId,3> pi{},qi{};
            for(unsigned k=0;k<3;++k) {
                pi[k]=static_cast<VertexId>(s.patch.faces[i][k])+1;
                qi[k]=static_cast<VertexId>(s.patch.faces[j][k])+1;
                p[k]=s.patch.positions[s.patch.faces[i][k]];
                q[k]=s.patch.positions[s.patch.faces[j][k]];
            }
            // Cheap conservative broad-phase: a spatially disjoint AABB
            // proves noncontact and does not spend a narrow-phase test.
            const auto apart=[&](auto coordinate) {
                const auto amin=std::min({coordinate(p[0]),coordinate(p[1]),
                                          coordinate(p[2])});
                const auto amax=std::max({coordinate(p[0]),coordinate(p[1]),
                                          coordinate(p[2])});
                const auto bmin=std::min({coordinate(q[0]),coordinate(q[1]),
                                          coordinate(q[2])});
                const auto bmax=std::max({coordinate(q[0]),coordinate(q[1]),
                                          coordinate(q[2])});
                return amax<bmin||bmax<amin;
            };
            if(apart([](Vec3 v){return v.x;})||
               apart([](Vec3 v){return v.y;})||
               apart([](Vec3 v){return v.z;}))continue;
            if(++tests>limits.maxIntersectionTests)
                throw std::length_error(
                    "R06-M22B advancing-front contact budget front="+
                    std::to_string(s.front.size())+
                    " faces="+std::to_string(s.patch.faces.size())+
                    " attempts="+std::to_string(attempts));
            const auto hit=triangleContact(p,pi,q,qi);
            if(hit!=TriangleContact::Disjoint&&
               hit!=TriangleContact::ExpectedAdjacency)return false;
        }
        return true;
    };
    // Work budget includes rejected proposals: never retry indefinitely.
    const auto maxAttempts=std::min<std::size_t>(
        limits.maxFaces*8+limits.maxBoundaryVertices*8,65536);
    // Every adaptive insertion must be followed by enough convex ear
    // closure to reduce the FRONT below its last committed size. Merely
    // insisting on one ear after two insertions permits net growth.
    bool requireNetReduction=false;
    std::size_t nextFrontTarget=n-1;
    while(state.front.size()>3) {
        if(++attempts>maxAttempts)
            throw std::length_error("R06-M22B advancing-front attempt budget");
        // Exact mirrored terminal: the final two half-disks close by one
        // shared real seam edge, NEVER by a crossing-plane triangle.
        if(limits.requireMirrorPlane&&state.front.size()==4) {
            std::vector<std::uint32_t> seams,off;
            for(const auto id:state.front)
                (state.patch.positions[id].x==0?seams:off).push_back(id);
            if(seams.size()==2&&off.size()==2&&
               state.twins[off[0]]==off[1]) {
                auto trial=state;
                // Find one candidate half triangle from cyclic front order.
                bool closed=false;
                for(std::size_t i=0;i<4&&!closed;++i) {
                    const auto a=trial.front[i];
                    const auto b=trial.front[(i+1)%4];
                    const auto d=trial.front[(i+2)%4];
                    if(trial.patch.positions[a].x==0&&
                       trial.patch.positions[d].x==0&&
                       trial.patch.positions[b].x!=0) {
                        addFace(trial,a,b,d);
                        addFace(trial,
                                static_cast<std::uint32_t>(state.twins[d]),
                                static_cast<std::uint32_t>(state.twins[b]),
                                static_cast<std::uint32_t>(state.twins[a]));
                        trial.front.clear();
                        if(legal(trial)){state=std::move(trial);closed=true;}
                        else throw std::logic_error(
                            "R06-M22B symmetric terminal half-disks not embedded");
                    }
                }
                if(closed)break;
            }
        }
        // Evaluate all corners, preferring the smallest oriented angle.
        // Reflected off-seam corners form one indivisible orbit.
        struct Corner {std::size_t index;double angle;};
        std::vector<Corner> choices;
        for(std::size_t i=0;i<state.front.size();++i) {
            const auto id=state.front[i];
            if(limits.requireMirrorPlane&&state.twins[id]<id)continue;
            const auto a=state.patch.positions[state.front[
                (i+state.front.size()-1)%state.front.size()]];
            const auto b=state.patch.positions[id];
            const auto d=state.patch.positions[state.front[
                (i+1)%state.front.size()]];
            const auto u=a-b,v=d-b;
            if(!(length(u)>1e-12&&length(v)>1e-12))continue;
            double theta=std::acos(std::clamp(
                dot(u,v)/(length(u)*length(v)),-1.,1.));
            if(dot(cross(u,v),normal)>1e-10*length(u)*length(v))
                theta=2*std::acos(-1.)-theta;
            choices.push_back({i,theta});
        }
        std::stable_sort(choices.begin(),choices.end(),
            [](const Corner& a,const Corner& b) {
                if(a.angle!=b.angle)return a.angle<b.angle;
                return a.index<b.index;
            });
        bool accepted=false;
        for(const auto& choice:choices) {
            if(accepted)break;
            const auto size=state.front.size();
            const auto at=choice.index;
            const auto vId=state.front[at];
            const auto aId=state.front[(at+size-1)%size];
            const auto bId=state.front[(at+1)%size];
            const auto vertex=state.patch.positions[vId];
            const auto a=state.patch.positions[aId];
            const auto b=state.patch.positions[bId];
            const auto ua=a-vertex,ub=b-vertex;
            const auto la=length(ua),lb=length(ub);
            if(!(la>1e-12&&lb>1e-12))continue;
            const auto dirA=ua/la,dirB=ub/lb;
            const auto bisector=dirA+dirB;
            const auto bisectorLen=length(bisector);
            const bool seam=limits.requireMirrorPlane&&vertex.x==0;
            const auto pi=std::acos(-1.);
            unsigned mode=seam?2:
                (choice.angle<=75*pi/180?1:
                 choice.angle<=135*pi/180?2:3);
            // The paper's 2/3-face turns can leave the front unchanged
            // or grow it. Once one is used, close convex ears until the
            // new front is STRICTLY smaller than it was before that turn.
            // A mirror-plane vertex retains its compulsory two-face mode.
            if(!seam&&requireNetReduction&&choice.angle<pi)
                mode=1;
            if(mode!=1&&!(bisectorLen>1e-10))continue;
            for(const double factor:{.7,1.0,.45}) {
                if(accepted)break;
                if(++attempts>maxAttempts)
                    throw std::length_error("R06-M22B front proposal budget");
                AdaptiveFrontState trial=state;
                std::vector<std::uint32_t> replacement;
                std::vector<std::array<std::uint32_t,3>> localFaces;
                if(mode==1) {
                    localFaces.push_back({aId,vId,bId});
                }else {
                    std::vector<Vec3> proposals;
                    if(seam&&choice.angle<75*pi/180) {
                        // Two mirrored right triangles, seam midpoint.
                        proposals.push_back({0,(a.y+b.y)*.5,(a.z+b.z)*.5});
                    }else if(mode==2) {
                        auto q=vertex+bisector/bisectorLen*
                            (factor*std::min(la,lb));
                        if(seam)q.x=0;
                        proposals.push_back(q);
                    }else {
                        auto first=dirA*2.+dirB;
                        auto second=dirA+dirB*2.;
                        if(!(length(first)>1e-12&&length(second)>1e-12))
                            continue;
                        proposals.push_back(vertex+normalized(first)*
                            (factor*std::min(la,lb)));
                        proposals.push_back(vertex+normalized(second)*
                            (factor*std::min(la,lb)));
                    }
                    bool rejected=false;
                    for(std::size_t ordinal=0;ordinal<proposals.size();++ordinal) {
                        auto q=proposals[ordinal];
                        // M23A: zero work and identical floating-point behavior
                        // for the null path. This hook is used only for proposed
                        // new positions, BEFORE any snap, contact or face test.
                        if(placementAdjustment) {
                            q=(*placementAdjustment)(SpatialCapPlacementProposal{
                                q,vertex,a,b,std::min(la,lb),
                                at,vId,aId,bId,mode,ordinal,
                                state.originSides[vId],&state.patch.positions,
                                &state.front,&state.originSides});
                        }
                        if(!finite(q)){rejected=true;break;}
                        if(limits.requireMirrorPlane&&!seam) {
                            const auto h=std::min(la,lb);
                            const bool crossing=vertex.x*q.x<0;
                            if(crossing||std::abs(q.x)<=
                               limits.nearSeamSnapFraction*h) {
                                // Distinct *candidate* positions; do not
                                // force a topologically pinched seam.
                                if(crossing) {
                                    const auto t=vertex.x/(vertex.x-q.x);
                                    q=vertex+(q-vertex)*t;
                                }
                                q.x=0;
                            }
                        }
                        if(length(q-vertex)<1e-10*rimScale) {
                            rejected=true;break;
                        }
                        const auto id=static_cast<std::uint32_t>(
                            trial.patch.positions.size());
                        trial.patch.positions.push_back(q);
                        trial.guides.push_back(state.guides[vId]);
                        trial.twins.push_back(id);
                        trial.originSides.push_back(state.originSides[vId]);
                        if(limits.requireMirrorPlane&&q.x!=0) {
                            const auto mate=static_cast<std::uint32_t>(
                                trial.patch.positions.size());
                            trial.patch.positions.push_back(reflect(q));
                            trial.guides.push_back(reflect(state.guides[vId]));
                            trial.twins.push_back(id);
                            trial.originSides.push_back(
                                state.originSides[vId]==1?2:
                                state.originSides[vId]==2?1:0);
                            trial.twins[id]=mate;
                        }else if(limits.requireMirrorPlane) {
                            trial.guides[id].x=0;
                        }
                        replacement.push_back(id);
                    }
                    if(rejected)continue;
                    if(mode==2) {
                        localFaces.push_back({aId,vId,replacement[0]});
                        localFaces.push_back({vId,bId,replacement[0]});
                    }else {
                        localFaces.push_back({aId,vId,replacement[0]});
                        localFaces.push_back({vId,replacement[1],replacement[0]});
                        localFaces.push_back({vId,bId,replacement[1]});
                    }
                }
                for(const auto& tri:localFaces) {
                    addFace(trial,tri[0],tri[1],tri[2]);
                    if(limits.requireMirrorPlane&&!seam)
                        addFace(trial,
                            static_cast<std::uint32_t>(trial.twins[tri[2]]),
                            static_cast<std::uint32_t>(trial.twins[tri[1]]),
                            static_cast<std::uint32_t>(trial.twins[tri[0]]));
                }
                // Replace the selected front corner and its mirrored
                // counterpart in the SAME original cyclic walk.
                std::vector<std::uint32_t> newFront;
                newFront.reserve(size+4);
                for(std::size_t j=0;j<size;++j) {
                    const auto old=state.front[j];
                    if(j==at) {
                        newFront.insert(newFront.end(),
                            replacement.begin(),replacement.end());
                    }else if(limits.requireMirrorPlane&&!seam&&
                             old==state.twins[vId]) {
                        for(auto it=replacement.rbegin();it!=replacement.rend();++it)
                            newFront.push_back(static_cast<std::uint32_t>(
                                trial.twins[*it]));
                    }else newFront.push_back(old);
                }
                trial.front=std::move(newFront);
                if(!legal(trial))continue;
                if(trial.front.size()<=nextFrontTarget) {
                    requireNetReduction=false;
                    nextFrontTarget=trial.front.empty()?0:trial.front.size()-1;
                }else requireNetReduction=true;
                state=std::move(trial);
                accepted=true;
            }
        }
        if(!accepted) {
            if(rimSides) {
                throw std::logic_error(
                    "R06-M23B advancing-front dead end front="+
                    std::to_string(state.front.size())+
                    " seed_boundary="+std::to_string(n)+
                    " generated_faces="+std::to_string(state.patch.faces.size())+
                    " attempts="+std::to_string(attempts)+
                    " require_mirror="+std::to_string(limits.requireMirrorPlane));
            }
            throw std::logic_error(
                "R06-M22B no admissible advancing-front mirrored operation");
        }
    }
    if(state.front.size()==3) {
        if(limits.requireMirrorPlane)
            throw std::logic_error("R06-M22B symmetric front reached odd terminal face");
        addFace(state,state.front[0],state.front[1],state.front[2]);
        state.front.clear();
    }
    if(!state.front.empty()||!legal(state))
        throw std::logic_error("R06-M22B final advancing-front patch invalid");
    std::vector<Vec3> interior;
    interior.reserve(state.patch.positions.size()-n);
    for(std::size_t i=n;i<state.patch.positions.size();++i)
        interior.push_back(state.guides[i]);
    solveSpatialCapFixedRimPoisson(state.patch,interior,limits,
        limits.requireMirrorPlane?state.twins:
            std::vector<std::size_t>{});
    return state.patch;
}
} // namespace

SpatialCapPatch buildSpatialCapFrontPoisson(
    const std::vector<Vec3>& orientedCapRim,
    const std::vector<Vec3>& survivingFaceNormals,
    const SpatialCapSettings& limits,
    const std::vector<SurvivorDirectionalCurvature>* incomingReference,
    const SpatialCapPlacementAdjustment* placementAdjustment,
    const std::vector<std::uint8_t>* boundarySides) {
    const auto n=orientedCapRim.size();
    if(n<3||n>limits.maxBoundaryVertices||
       (!limits.useAdvancingFront&&
        (n+1>limits.maxInteriorVertices||n*3>limits.maxFaces))||
       !limits.maxPoissonIterations||!limits.maxIntersectionTests||
       !std::isfinite(limits.poissonTolerance)||
       !std::isfinite(limits.maximumInitialEdgeFactor)||
       !std::isfinite(limits.normalGuidance)||
       limits.poissonTolerance<=0||limits.maximumInitialEdgeFactor<=1||
       limits.normalGuidance<0||limits.normalGuidance>.5||
       (limits.curvatureGuidedPoisson&&
        (!limits.maxCurvaturePoissonIterations||
         !std::isfinite(limits.curvaturePoissonStrength)||
         !(limits.curvaturePoissonStrength>0)||
         limits.curvaturePoissonStrength>8||
         !std::isfinite(limits.curvaturePoissonAnchorWeight)||
         limits.curvaturePoissonAnchorWeight<0||
         limits.curvaturePoissonAnchorWeight>8||
         !std::isfinite(limits.curvaturePoissonMaxNormalShift)||
         !(limits.curvaturePoissonMaxNormalShift>0)||
         limits.curvaturePoissonMaxNormalShift>2))||
       (limits.optimizeBoundaryContinuity&&
        (!limits.maxContinuityRounds||!limits.maxContinuityTrials||
         !std::isfinite(limits.desiredMinimumQuality)||
         limits.desiredMinimumQuality<=0||
         limits.desiredMinimumQuality>=1))||
       (limits.repairTangentialOvershoot&&
        (!std::isfinite(limits.desiredMinimumQuality)||
         limits.desiredMinimumQuality<=0||
         limits.desiredMinimumQuality>=1||
         !limits.maxCorrectionRounds||!limits.maxCorrectionTrials)))
        throw std::length_error("R06-M06C spatial front finite-work limits refused");
    if(!survivingFaceNormals.empty()&&survivingFaceNormals.size()!=n)
        throw std::invalid_argument("R06-M06C front normals not indexed to cap rim");
    if(incomingReference&&incomingReference->size()!=n)
        throw std::invalid_argument("R06-M18D incoming survivor tensor orbit mismatch");
    if(placementAdjustment&&!limits.useAdvancingFront)
        throw std::invalid_argument("R06-M23A placement adjustment requires advancing-front mode");
    if(boundarySides&&(!limits.useAdvancingFront||
       boundarySides->size()!=n||
       std::any_of(boundarySides->begin(),boundarySides->end(),
           [](std::uint8_t side){return side>2;})))
        throw std::invalid_argument("R06-M23B invalid advancing-front ancestry");

    SpatialCapPatch result;
    result.boundaryCount=n;
    result.positions=orientedCapRim;
    Vec3 center{};
    std::vector<double> originalEdges;
    originalEdges.reserve(n);
    for(std::size_t i=0;i<n;++i) {
        const auto a=orientedCapRim[i];
        const auto b=orientedCapRim[(i+1)%n];
        if(!finite(a)||!finite(b))
            throw std::logic_error("R06-M06C front nonfinite rim position");
        center=center+a;
        originalEdges.push_back(length(b-a));
    }
    center=center/static_cast<double>(n);
    if(limits.requireMirrorPlane)center.x=0;
    std::sort(originalEdges.begin(),originalEdges.end());
    const auto h=originalEdges[n/2];
    if(!(h>1e-12)||!std::isfinite(h))
        throw std::logic_error("R06-M06C front degenerate edge scale");

    const auto reflect=[](Vec3 p) {return Vec3{-p.x,p.y,p.z};};
    std::vector<std::size_t> partner(2*n+1);
    if(limits.requireMirrorPlane) {
        std::size_t seam=0;
        for(std::size_t i=0;i<n;++i) {
            const auto p=orientedCapRim[i];
            if(p.x==0)++seam;
            std::size_t match=n;
            for(std::size_t j=0;j<n;++j) {
                const auto q=orientedCapRim[j];
                // Do not infer topology from approximate mirror proximity.
                // Exact source-symmetry coordinates are necessary here.
                if(q.x!=-p.x||q.y!=p.y||q.z!=p.z)continue;
                if(match!=n)
                    throw std::logic_error(
                        "R06-M06C ambiguous mirrored boundary identity");
                match=j;
            }
            if(match==n)
                throw std::logic_error(
                    "R06-M06C missing exact mirrored boundary vertex");
            partner[i]=match;
        }
        if(seam!=2)
            throw std::logic_error(
                "R06-M06C reflected spatial disk requires exactly two existing X=0 seam vertices");
        for(std::size_t i=0;i<n;++i) {
            if(partner[partner[i]]!=i)
                throw std::logic_error(
                    "R06-M06C noninvolutive reflected rim orbit");
            const auto j=(i+1)%n;
            if(orientedCapRim[i].x*orientedCapRim[j].x<0)
                throw std::logic_error(
                    "R06-M06C boundary edge crosses X=0 without an actual seam vertex");
            partner[n+i]=n+partner[i];
        }
        partner[2*n]=2*n;
    }

    if(limits.useAdvancingFront) {
        auto patch=constructAdaptiveFront(
            orientedCapRim,survivingFaceNormals,partner,limits,
            placementAdjustment,boundarySides);
        // Generic AFM patches have no positional one-to-one n-ring or hub.
        // Intentionally bypass M17–M21 ring-index optimizations here.
        std::size_t tests=0;
        patch.minimumQuality=1.;
        for(const auto& face:patch.faces) {
            const auto a=patch.positions[face[0]],b=patch.positions[face[1]],
                       c=patch.positions[face[2]];
            const auto q=quality(a,b,c);
            if(!(q>1e-8&&std::isfinite(q)))
                throw std::logic_error("R06-M22B Poisson collapsed advancing-front face");
            patch.minimumQuality=std::min(patch.minimumQuality,q);
            if(std::max({length(a-b),length(b-c),length(c-a)})>
               h*limits.maximumInitialEdgeFactor)
                throw std::logic_error("R06-M22B advancing-front edge scale exceeded");
        }
        for(std::size_t x=0;x<patch.faces.size();++x)
        for(std::size_t y=x+1;y<patch.faces.size();++y) {
            if(++tests>limits.maxIntersectionTests)
                throw std::length_error("R06-M22B final cap contact budget");
            std::array<Vec3,3> a{},b{};
            std::array<VertexId,3> ai{},bi{};
            for(unsigned k=0;k<3;++k) {
                ai[k]=patch.faces[x][k]+1;
                bi[k]=patch.faces[y][k]+1;
                a[k]=patch.positions[patch.faces[x][k]];
                b[k]=patch.positions[patch.faces[y][k]];
            }
            const auto contact=triangleContact(a,ai,b,bi);
            if(contact!=TriangleContact::Disjoint&&
               contact!=TriangleContact::ExpectedAdjacency)
                throw std::logic_error("R06-M22B settled advancing-front self contact");
        }
        return patch;
    }

    // Advance the oriented FRONT one local mesh layer. The front is the
    // actual 3D rim, rather than a flattened projected polygon. Later
    // patch-vs-patch and candidate-vs-survivor audits may reject a folded
    // front whose interpolated inward ring crosses another surface.
    std::vector<Vec3> normals(n);
    Vec3 averageNormal{};
    for(std::size_t i=0;i<n;++i) {
        const auto source=survivingFaceNormals.empty()?
            Vec3{}:survivingFaceNormals[i];
        if(!finite(source))
            throw std::logic_error("R06-M06C front nonfinite source normal");
        const auto norm=length(source);
        if(norm>1e-12)normals[i]=source/norm;
        averageNormal=averageNormal+normals[i];
        result.positions.push_back(orientedCapRim[i]*.55+center*.45);
    }
    if(limits.requireMirrorPlane) {
        for(std::size_t i=0;i<n;++i) {
            const auto j=partner[i];
            if(j<i)continue;
            if(j==i) {
                normals[i].x=0;
                result.positions[n+i].x=0;
                continue;
            }
            const auto v=(normals[i]+reflect(normals[j]))*.5;
            normals[i]=v;
            normals[j]=reflect(v);
            const auto p=(result.positions[n+i]+
                         reflect(result.positions[n+j]))*.5;
            result.positions[n+i]=p;
            result.positions[n+j]=reflect(p);
        }
        averageNormal={};
        for(const auto v:normals)averageNormal=averageNormal+v;
        averageNormal.x=0;
    }
    const auto normalLength=length(averageNormal);
    if(normalLength>1e-12)averageNormal=averageNormal/normalLength;
    result.positions.push_back(center);
    const auto hub=static_cast<std::uint32_t>(2*n);

    // The outward surface and inward ring share every ORIGINAL rim edge
    // exactly once. The last ring front is closed to an interior hub.
    for(std::uint32_t i=0;i<n;++i) {
        const auto j=static_cast<std::uint32_t>((i+1)%n);
        const auto a=i,b=j,c=static_cast<std::uint32_t>(n)+j;
        const auto d=static_cast<std::uint32_t>(n)+i;
        // Diagonals on opposite half-disks must be reflected, not
        // independently chosen by the cyclic walk. Otherwise the
        // interiors are geometrically reflected but triangle IDs/
        // connectivity are NOT mirrored.
        const bool negativeHalf=limits.requireMirrorPlane&&
            (result.positions[a].x<0||result.positions[b].x<0);
        if(negativeHalf!=limits.alternateBandDiagonals) {
            result.faces.push_back({a,b,d});
            result.faces.push_back({b,c,d});
        }else {
            result.faces.push_back({a,b,c});
            result.faces.push_back({a,c,d});
        }
        result.faces.push_back({d,c,hub});
    }

    if(limits.requireMirrorPlane) {
        // A disk crossing the reflection plane is triangulated as TWO
        // mirrored half-disks, joined by real X=0 seam vertices/edges.
        // Off-plane triangles may never bridge the plane directly.
        const auto cyclic=[](const auto& a,const auto& b) {
            for(unsigned shift=0;shift<3;++shift)
                if(a[0]==b[shift]&&a[1]==b[(shift+1)%3]&&
                   a[2]==b[(shift+2)%3])return true;
            return false;
        };
        for(const auto& t:result.faces) {
            const auto x0=result.positions[t[0]].x;
            const auto x1=result.positions[t[1]].x;
            const auto x2=result.positions[t[2]].x;
            if(std::min({x0,x1,x2})<0&&std::max({x0,x1,x2})>0)
                throw std::logic_error(
                    "R06-M06C reflected front has an off-plane triangle crossing the seam");
            const std::array<std::uint32_t,3> twin{
                static_cast<std::uint32_t>(partner[t[0]]),
                static_cast<std::uint32_t>(partner[t[2]]),
                static_cast<std::uint32_t>(partner[t[1]])};
            if(std::none_of(result.faces.begin(),result.faces.end(),
                [&](const auto& candidate){return cyclic(twin,candidate);}))
                throw std::logic_error(
                    "R06-M06C reflected front lacks paired reversed-winding triangle");
        }
    }

    // M22A: legacy n-ring+hub coordinates now go through the SAME
    // topology-agnostic solver used by future advancing-front patches.
    // Retain precisely the original per-ring and hub guidance field.
    std::vector<Vec3> interiorGuidance=normals;
    interiorGuidance.push_back(averageNormal);
    solveSpatialCapFixedRimPoisson(result,interiorGuidance,limits,
        limits.requireMirrorPlane?partner:std::vector<std::size_t>{});

    std::size_t tests=0;
    const auto embedded=[&](SpatialCapPatch& candidate) {
            // Validate each candidate as a genuine finite embedded 3D disk. This pairwise
        // test is finite by construction; uncertain contacts are refusals.
        for(std::size_t i=0;i<candidate.faces.size();++i) {
            const auto& ids=candidate.faces[i];
            const auto a=candidate.positions[ids[0]];
            const auto b=candidate.positions[ids[1]];
            const auto c=candidate.positions[ids[2]];
            const auto q=quality(a,b,c);
            if(q<=1e-8||!std::isfinite(q))
                throw std::logic_error("R06-M06C zero-area or collapsed spatial front triangle");
            candidate.minimumQuality=std::min(candidate.minimumQuality,q);
            const auto longest=std::max({length(a-b),length(b-c),length(c-a)});
            if(longest>h*limits.maximumInitialEdgeFactor)
                throw std::logic_error("R06-M06C front triangles exceed finite local edge scale");
        }
        for(std::size_t i=0;i<candidate.faces.size();++i) {
            std::array<Vec3,3> a;
            std::array<VertexId,3> ai;
            for(unsigned k=0;k<3;++k) {
                ai[k]=static_cast<VertexId>(candidate.faces[i][k])+1;
                a[k]=candidate.positions[candidate.faces[i][k]];
            }
            for(std::size_t j=i+1;j<candidate.faces.size();++j) {
                if(++tests>limits.maxIntersectionTests)
                    throw std::length_error("R06-M06C front pairwise intersection budget");
                std::array<Vec3,3> b;
                std::array<VertexId,3> bi;
                for(unsigned k=0;k<3;++k) {
                    bi[k]=static_cast<VertexId>(candidate.faces[j][k])+1;
                    b[k]=candidate.positions[candidate.faces[j][k]];
                }
                const auto contact=triangleContact(a,ai,b,bi);
                if(contact!=TriangleContact::Disjoint&&
                   contact!=TriangleContact::ExpectedAdjacency)
                    return false;
            }
        }
        return true;
    };
    if(limits.preferMirroredRibbonForTesting) {
        if(!limits.requireMirrorPlane)
            throw std::invalid_argument("R06-M06C test ribbon requires mirror plane");
        auto ribbon=mirroredRibbon(orientedCapRim,partner,limits);
        if(embedded(ribbon))return ribbon;
        throw std::logic_error("R06-M06C test mirrored ribbon self-intersects");
    }
    const bool initiallyEmbedded=embedded(result);
    if(initiallyEmbedded&&limits.repairTangentialOvershoot&&
       result.minimumQuality<limits.desiredMinimumQuality) {
        // A Poisson-solved ring point can lie PAST its owning R03 boundary
        // corner in the local rim tangent direction. In refusal-1 the
        // minimum-q strip face projects its ring tip at t=1.4867 along
        // a preceding rim edge, creating a near-zero-area return.
        // Changing the initial 55/45 seed cannot alter the converged
        // Poisson solution. Search the SETTLED ring positions instead.
        if(!std::isfinite(limits.desiredMinimumQuality)||
           limits.desiredMinimumQuality<=0||
           limits.desiredMinimumQuality>=1||
           !limits.maxCorrectionRounds||!limits.maxCorrectionTrials)
            throw std::invalid_argument(
                "R06-M17D requires finite positive ring-correction budget");
        SpatialCapPatch current=result;
        std::size_t trials=0;
        const auto minimum=[&](const SpatialCapPatch& p) {
            double worst=1.;
            std::size_t worstFace=p.faces.size();
            for(std::size_t j=0;j<p.faces.size();++j) {
                const auto& face=p.faces[j];
                const auto q=quality(p.positions[face[0]],
                                     p.positions[face[1]],
                                     p.positions[face[2]]);
                if(q<worst) {worst=q;worstFace=j;}
            }
            return std::pair<double,std::size_t>{worst,worstFace};
        };
        for(std::size_t round=0;round<limits.maxCorrectionRounds;++round) {
            const auto [q,worstIndex]=minimum(current);
            if(q>=limits.desiredMinimumQuality||
               worstIndex>=current.faces.size()||
               trials>=limits.maxCorrectionTrials)break;
            // Restrict movement to inward-ring vertices participating in
            // the current WORST triangle. No survivor/rim, hub or other
            // arbitrary part of the mesh is allowed to move.
            SpatialCapPatch best=current;
            double bestQ=q;
            std::set<std::size_t> ringChoices;
            for(const auto id:current.faces[worstIndex])
                if(id>=n&&id<2*n)
                    ringChoices.insert(static_cast<std::size_t>(id));
            for(const auto vertex:ringChoices) {
                const auto i=vertex-n;
                const auto from=orientedCapRim[i];
                const auto starting=current.positions[vertex];
                const auto mate=limits.requireMirrorPlane?
                    partner[vertex]:vertex;
                // Rim tangents point toward the current fixed R03 vertex.
                // A positive projection of (ring-fixed) onto a tangent
                // means the new vertex overshot the contour at that corner.
                for(const auto neighbor:{
                        (i+n-1)%n,(i+1)%n}) {
                    const auto tangent=from-orientedCapRim[neighbor];
                    const auto size2=dot(tangent,tangent);
                    if(!(size2>1e-20))continue;
                    const auto overshoot=dot(starting-from,tangent)/size2;
                    if(!(overshoot>.05))continue;
                    // The original failure lies almost exactly ON the
                    // supporting line. Sliding along that line alone can
                    // relocate the sliver. Also evaluate moving PERPENDICULAR
                    // to the line, retaining the observed inward half-plane
                    // rather than inventing a new surface-normal direction.
                    const auto lateral=(starting-from)-tangent*overshoot;
                    for(const double fraction:{0.5,1.,1.5,2.})
                    for(const double transverse:{1.,2.,3.}) {
                        if(trials>=limits.maxCorrectionTrials)break;
                        const auto movement=tangent*(overshoot*fraction)-
                                            lateral*(transverse-1.);
                        if(length(movement)>1.5*h)continue;
                        const auto moved=starting-movement;
                        if(!finite(moved))continue;
                        if(limits.requireMirrorPlane&&mate!=vertex&&
                           moved.x*starting.x<0)continue;
                        auto proposed=current;
                        proposed.positions[vertex]=moved;
                        if(mate==vertex)
                            proposed.positions[vertex].x=0;
                        else
                            proposed.positions[mate]=reflect(moved);
                        // Reject local normal reversal on every incident
                        // face BEFORE the expensive complete self-contact
                        // audit. In particular an old needle must not be
                        // repaired by turning its cap inside out.
                        bool orientation=true;
                        for(const auto& tri:current.faces) {
                            if(std::find(tri.begin(),tri.end(),
                                         static_cast<std::uint32_t>(vertex))
                                   ==tri.end()&&
                               std::find(tri.begin(),tri.end(),
                                         static_cast<std::uint32_t>(mate))
                                   ==tri.end())continue;
                            const auto old=cross(
                                current.positions[tri[1]]-current.positions[tri[0]],
                                current.positions[tri[2]]-current.positions[tri[0]]);
                            const auto updated=cross(
                                proposed.positions[tri[1]]-proposed.positions[tri[0]],
                                proposed.positions[tri[2]]-proposed.positions[tri[0]]);
                            if(length(updated)<=1e-16||dot(old,updated)<=0) {
                                orientation=false;break;
                            }
                        }
                        if(!orientation)continue;
                        const auto [trialQ,unusedIndex]=minimum(proposed);
                        (void)unusedIndex;
                        if(!(trialQ>bestQ+1e-6))continue;
                        // A proposal may improve the original q=.061
                        // needle by CREATING a new q=.08 needle elsewhere.
                        // Never turn an initially accepted q>=hard-floor
                        // triangle into an unaccepted one to subsidize it.
                        bool keepsHealthyFaces=true;
                        for(const auto& tri:current.faces) {
                            const auto before=quality(
                                current.positions[tri[0]],
                                current.positions[tri[1]],
                                current.positions[tri[2]]);
                            const auto after=quality(
                                proposed.positions[tri[0]],
                                proposed.positions[tri[1]],
                                proposed.positions[tri[2]]);
                            if(before>=limits.desiredMinimumQuality&&
                               after+1e-12<limits.desiredMinimumQuality) {
                                keepsHealthyFaces=false;break;
                            }
                        }
                        if(!keepsHealthyFaces)continue;
                        proposed.minimumQuality=1.;
                        ++trials;
                        // Use the SAME bounded full self-contact and
                        // local edge-scale validation as the primary
                        // spatial patch. No lower q tolerance or omitted
                        // pairwise checks for a proposed new position.
                        try {
                            if(!embedded(proposed))continue;
                        }catch(const std::logic_error&) {
                            continue;
                        }
                        if(proposed.minimumQuality>bestQ+1e-6) {
                            bestQ=proposed.minimumQuality;
                            best=std::move(proposed);
                        }
                    }
                }
            }
            if(bestQ<=q+1e-6)break;
            current=std::move(best);
        }
        if(current.minimumQuality>result.minimumQuality+1e-6)
            result=std::move(current);
    }
    // M18E: solve a new, fixed-rim Poisson objective, not a replacement
    // initial seed. The source tensor defines a second-order normal
    // continuation whose trace on each original rim EDGE remains zero.
    // Existing baseline candidate is retained unless a finite, embedded,
    // quality-preserving second solve measurably improves continuity.
    if(initiallyEmbedded&&limits.curvatureGuidedPoisson&&incomingReference&&
       !survivingFaceNormals.empty()) {
        // M18E remains an optional legacy RING-based second solve. Its
        // graph and baseline source must be local to this experiment:
        // M22A moved the ordinary graph Poisson into a generic patch
        // solver, so the old outer-scope variables no longer exist.
        // Do not apply this index-specific refinement to future AFM caps.
        std::vector<std::set<std::uint32_t>> adjacent(result.positions.size());
        for(const auto& face:result.faces)
            for(unsigned k=0;k<3;++k) {
                const auto a=face[k],b=face[(k+1)%3];
                adjacent[a].insert(b);
                adjacent[b].insert(a);
            }
        const auto sourceAt=[&](std::size_t index) {
            const auto direction=index<2*n?normals[index-n]:averageNormal;
            const auto degree=static_cast<double>(adjacent[index].size());
            return direction*(limits.normalGuidance*h*degree);
        };
        const auto tolerance=limits.poissonTolerance*h;
        struct Constraint {Vec3 normal;double projection,weight;};
        std::vector<std::vector<Constraint>> constraints(result.positions.size());
        const auto rimProfile=measureSpatialCapRimProfile(result,survivingFaceNormals);
        for(const auto& edge:rimProfile.edges) {
            const auto j=edge.rimEnd;
            const auto& source=(*incomingReference)[j];
            if(!edge.hasSurvivorNormal||!edge.hasCapNormal||
               !source.hasEstimate||
               source.confidence!=SurvivorCurvatureConfidence::Reliable||
               source.confidenceScore<.20)continue;
            const auto vertex=edge.capOppositeVertex;
            if(vertex<n||vertex>=2*n)continue;
            const auto a=result.positions[edge.rimStart];
            const auto b=result.positions[edge.rimEnd];
            const auto p=result.positions[vertex];
            const auto normal=survivingFaceNormals[j]/
                length(survivingFaceNormals[j]);
            const auto t=(b-a)/edge.edgeLength;
            const auto u=cross(normal,t);
            const auto x=std::clamp(dot(p-a,t),0.,edge.edgeLength);
            const auto y=std::clamp(dot(p-a,u),-h,h);
            // Along-seam term vanishes at BOTH fixed rim endpoints;
            // cross and mixed curvature remain directional. Project
            // to a scale-bounded tensor before extrapolating.
            const auto safe=[&](double curvature) {
                return std::clamp(curvature,-.7/h,.7/h);
            };
            const auto desired=.5*safe(source.seam)*x*(x-edge.edgeLength)+
                safe(source.mixed)*(x-.5*edge.edgeLength)*y+
                .5*safe(source.transverse)*y*y;
            const auto oldHeight=dot(p-a,normal);
            const auto shift=std::clamp(desired-oldHeight,
                -limits.curvaturePoissonMaxNormalShift*h,
                limits.curvaturePoissonMaxNormalShift*h);
            const auto weight=limits.curvaturePoissonStrength*
                source.confidenceScore;
            constraints[vertex].push_back({
                normal,dot(p+normal*shift,normal),weight});
        }
        std::size_t constrained=0;
        for(std::size_t k=n;k<2*n;++k)
            if(!constraints[k].empty())++constrained;
        if(constrained) {
            SpatialCapPatch guided=result;
            bool guidedConverged=false;
            std::size_t guidedIterations=0;
            double residual=0;
            for(std::size_t iteration=0;
                iteration<limits.maxCurvaturePoissonIterations;++iteration) {
                ++guidedIterations;
                // Jacobi even on nonmirrored cap: no ordering bias in
                // second-order data, exact mirrored orbit projection.
                auto next=guided.positions;
                for(std::size_t i=n;i<guided.positions.size();++i) {
                    Vec3 rhs=sourceAt(i);
                    for(const auto neighbor:adjacent[i])
                        rhs=rhs+guided.positions[neighbor];
                    const auto degree=static_cast<double>(adjacent[i].size());
                    // The homogeneous second solve would otherwise
                    // destroy M17D's legal tangential in-ring repair.
                    // This quadratic anchor is part of the Poisson
                    // objective, not an after-solve vertex reset.
                    const auto anchor=constraints[i].empty()?0.:
                        degree*limits.curvaturePoissonAnchorWeight;
                    rhs=rhs+result.positions[i]*anchor;
                    const auto unconstrained=rhs/(degree+anchor);
                    Vec3 projected=unconstrained;
                    double totalWeight=0;
                    for(const auto& guide:constraints[i])
                        totalWeight+=guide.weight;
                    for(const auto& guide:constraints[i]) {
                        const auto alpha=guide.weight/
                            (degree+anchor+totalWeight);
                        projected=projected+guide.normal*(
                            alpha*(guide.projection-
                                   dot(unconstrained,guide.normal)));
                    }
                    if(!finite(projected))
                        throw std::logic_error(
                            "R06-M18E guided Poisson nonfinite interior");
                    next[i]=projected;
                }
                if(limits.requireMirrorPlane) {
                    for(std::size_t i=n;i<next.size();++i) {
                        const auto mate=partner[i];
                        if(mate<i)continue;
                        if(mate==i)next[i].x=0;
                        else {
                            const auto mean=(next[i]+reflect(next[mate]))*.5;
                            next[i]=mean;
                            next[mate]=reflect(mean);
                        }
                    }
                }
                residual=0;
                for(std::size_t i=n;i<next.size();++i)
                    residual=std::max(residual,
                        length(next[i]-guided.positions[i]));
                guided.positions=std::move(next);
                if(residual<=tolerance) {guidedConverged=true;break;}
            }
            bool accepted=false;
            double beforeScore=0,afterScore=0,selectedStrength=0;
            std::size_t failedOrientation=0,failedQuality=0,
                        failedScore=0,failedContact=0,contactTests=0;
            bool contactBudgetExceeded=false;
            if(guidedConverged) {
                try {
                    const auto compare=[&](const SpatialCapPatch& patch) {
                        const auto continuity=measureSpatialCapContinuity(
                            patch,survivingFaceNormals,*incomingReference);
                        double objective=0;
                        for(const auto& edge:continuity.edges)
                            objective+=edge.boundaryNormalJumpRadians*
                                edge.boundaryNormalJumpRadians+
                                .25*edge.capInteriorFairnessRadians*
                                    edge.capInteriorFairnessRadians;
                        return std::pair<double,double>{
                            objective/static_cast<double>(n),
                            continuity.maximumBoundaryJumpRadians};
                    };
                    const auto baseline=compare(result);
                    beforeScore=baseline.first;
                    double bestScore=baseline.first;
                    SpatialCapPatch acceptedPatch=result;
                    // Damped guidance is a homotopy toward the converged
                    // constrained Poisson solution. An overstrong curvature
                    // term may invert a nearby cap triangle; reject that
                    // candidate, NOT the entire guidance experiment.
                    // Exactly three fixed, finite amplitudes; the same
                    // cumulative global embedding budget applies to all.
                    for(const double fraction:{.25,.5,1.}) {
                        SpatialCapPatch proposed=result;
                        for(std::size_t i=n;i<proposed.positions.size();++i)
                            proposed.positions[i]=result.positions[i]+
                                (guided.positions[i]-result.positions[i])*fraction;
                        bool legal=true;
                        double minimum=1.;
                        for(const auto& tri:result.faces) {
                            const auto beforeNormal=cross(
                                result.positions[tri[1]]-result.positions[tri[0]],
                                result.positions[tri[2]]-result.positions[tri[0]]);
                            const auto newNormal=cross(
                                proposed.positions[tri[1]]-proposed.positions[tri[0]],
                                proposed.positions[tri[2]]-proposed.positions[tri[0]]);
                            if(dot(beforeNormal,newNormal)<=0||
                               length(newNormal)<=1e-16) {
                                ++failedOrientation;legal=false;break;
                            }
                            minimum=std::min(minimum,quality(
                                proposed.positions[tri[0]],proposed.positions[tri[1]],
                                proposed.positions[tri[2]]));
                        }
                        if(!legal)continue;
                        if(result.minimumQuality>=limits.desiredMinimumQuality?
                           minimum+1e-12<limits.desiredMinimumQuality:
                           minimum+1e-12<result.minimumQuality) {
                            ++failedQuality;continue;
                        }
                        const auto proposedMetric=compare(proposed);
                        if(!(proposedMetric.first+1e-5<bestScore)||
                           proposedMetric.second>baseline.second+1e-8) {
                            ++failedScore;continue;
                        }
                        proposed.minimumQuality=1.;
                        ++contactTests;
                        try {
                            if(!embedded(proposed)) {
                                ++failedContact;continue;
                            }
                        }catch(const std::length_error&) {
                            contactBudgetExceeded=true;break;
                        }catch(const std::logic_error&) {
                            ++failedContact;continue;
                        }
                        if(proposed.minimumQuality+1e-12<
                           limits.desiredMinimumQuality&&
                           result.minimumQuality>=limits.desiredMinimumQuality) {
                            ++failedQuality;continue;
                        }
                        bestScore=proposedMetric.first;
                        afterScore=bestScore;
                        selectedStrength=fraction;
                        acceptedPatch=std::move(proposed);
                        accepted=true;
                    }
                    if(accepted) {
                        result=std::move(acceptedPatch);
                        result.poissonIterations+=guidedIterations;
                    }
                }catch(const std::exception&) {
                    // Missing/invalid guidance cannot alter a valid baseline.
                }
            }
            std::cerr<<"[repair-r06-m18e] constrained_ring_vertices="
                     <<constrained<<" converged="<<guidedConverged
                     <<" residual="<<residual
                     <<" guided_iterations="<<guidedIterations
                     <<" accepted="<<accepted
                     <<" before_score="<<beforeScore
                     <<" guided_score="<<afterScore
                     <<" selected_fraction="<<selectedStrength
                     <<" orientation_rejections="<<failedOrientation
                     <<" quality_rejections="<<failedQuality
                     <<" score_rejections="<<failedScore
                     <<" contact_rejections="<<failedContact
                     <<" contact_tests="<<contactTests
                     <<" contact_budget_exceeded="<<contactBudgetExceeded
                     <<" final_min_q="<<result.minimumQuality<<"\\n";
        }
    }
    // M18D is a separate opt-in from M17D. It works on the settled (and
    // possibly M17D-improved) patch, not the irrelevant initial Poisson seed.
    // A patch below the hard quality floor remains the old unmodified
    // result; M18D is not a replacement for M17D's skinny-triangle repair.
    if(initiallyEmbedded&&limits.optimizeBoundaryContinuity&&
       !result.usedMirroredRibbonFallback&&
       result.minimumQuality+1e-12>=limits.desiredMinimumQuality) {
        SpatialCapContinuityLimits continuityLimits;
        continuityLimits.maxPatchFaces=limits.maxFaces;
        // When the caller supplied no source tensor, retain first-order
        // diagnostics but NEVER manufacture reliable second-order evidence.
        std::vector<SurvivorDirectionalCurvature> blank(n);
        const auto& reference=incomingReference?*incomingReference:blank;
        SpatialCapPatch current=result;
        const auto score=[&](const SpatialCapContinuity& evaluation) {
            double energy=0;
            for(const auto& face:evaluation.edges) {
                const auto jump=face.boundaryNormalJumpRadians;
                const auto fair=face.capInteriorFairnessRadians;
                energy+=jump*jump+.25*fair*fair;
            }
            return energy/static_cast<double>(evaluation.edges.size());
        };
        SpatialCapContinuity comparison;
        try {
            comparison=measureSpatialCapContinuity(
                current,survivingFaceNormals,reference,continuityLimits);
        }catch(const std::exception&) {
            // A diagnostic failure does not turn a valid M17D closure
            // into a geometry refusal, even in the independent opt-in.
        }
        if(comparison.edges.size()==n) {
            const auto budgetPerEmbedding=
                current.faces.size()*(current.faces.size()-1)/2;
            std::size_t proposedTrials=0,acceptedMoves=0;
            double currentScore=score(comparison);
            bool exhausted=false;
            for(std::size_t round=0;
                round<limits.maxContinuityRounds&&!exhausted;++round) {
                // Only investigate visible discontinuities; a healthy cap
                // with smooth joins should not be gratuitously remodeled.
                std::vector<std::size_t> ordinals(n);
                std::iota(ordinals.begin(),ordinals.end(),0);
                std::stable_sort(ordinals.begin(),ordinals.end(),
                    [&](std::size_t a,std::size_t b) {
                        return comparison.edges[a].boundaryAndFairnessScore>
                               comparison.edges[b].boundaryAndFairnessScore;
                    });
                SpatialCapPatch best=current;
                SpatialCapContinuity bestComparison=comparison;
                double bestScore=currentScore;
                for(const auto ordinal:ordinals) {
                    if(exhausted)break;
                    const auto& edgeState=comparison.edges[ordinal];
                    if(edgeState.boundaryNormalJumpRadians<.35&&
                       edgeState.capInteriorFairnessRadians<.8)
                        continue;
                    const auto vertex=
                        static_cast<std::size_t>(edgeState.rim.capOppositeVertex);
                    if(vertex<n||vertex>=2*n)continue;
                    const auto mate=limits.requireMirrorPlane?
                        partner[vertex]:vertex;
                    // The same mirrored source triangle is reached by a
                    // different rim ordinal; only one orbit proposal is
                    // considered in each search round.
                    if(mate<vertex)continue;
                    const auto a=current.positions[edgeState.rim.rimStart];
                    const auto b=current.positions[edgeState.rim.rimEnd];
                    const auto t=(b-a)/edgeState.rim.edgeLength;
                    const auto starting=current.positions[vertex];
                    const auto foot=a+t*dot(starting-a,t);
                    const auto relative=starting-foot;
                    const auto referenceFoot=edgeState.rim.oppositeFootParameter;
                    const auto repairedFoot=std::clamp(referenceFoot,.05,.95);
                    // Rotate the opposite corner about its EXACT boundary
                    // edge: an edge triangle's length/quality are preserved
                    // by rotation, unlike blind vertex-projection into the
                    // survivor tangent plane.
                    const auto dihedral=edgeState.rim.signedDihedralRadians;
                    for(const auto fraction:{.2,.4,.65,1.})
                    for(const auto footRepair:{0.,.65}) {
                        if(proposedTrials>=limits.maxContinuityTrials) {
                            exhausted=true;break;
                        }
                        const auto theta=std::clamp(-dihedral*fraction,-.9,.9);
                        if(std::abs(theta)<1.e-4&&
                           (footRepair==0.||referenceFoot==repairedFoot))
                            continue;
                        // Count every nontrivial proposal, including ones
                        // rejected by cheap q/embedding preflight. Otherwise
                        // the declared bound can hide thousands of costly
                        // M18C tensor evaluations on a large contour.
                        ++proposedTrials;
                        auto proposed=current;
                        const auto rotated=relative*std::cos(theta)+
                            cross(t,relative)*std::sin(theta);
                        const auto shift=t*((repairedFoot-referenceFoot)*
                            edgeState.rim.edgeLength*footRepair);
                        const auto moved=foot+rotated+shift;
                        if(!finite(moved)||length(moved-starting)>1.5*h)
                            continue;
                        if(limits.requireMirrorPlane&&mate!=vertex&&
                           moved.x*starting.x<0)
                            continue;
                        proposed.positions[vertex]=moved;
                        if(mate==vertex)
                            proposed.positions[vertex].x=0;
                        else
                            proposed.positions[mate]=reflect(moved);
                        // No inverted incident face, no new face under the
                        // original q>=.10 strict cap threshold, and no
                        // movement of any fixed rim or center hub.
                        bool legal=true;
                        for(const auto& tri:current.faces) {
                            const auto p=proposed.positions[tri[0]];
                            const auto q=proposed.positions[tri[1]];
                            const auto r=proposed.positions[tri[2]];
                            const auto qAfter=quality(p,q,r);
                            if(qAfter+1e-12<limits.desiredMinimumQuality){
                                legal=false;break;
                            }
                            if(std::find(tri.begin(),tri.end(),
                                         static_cast<std::uint32_t>(vertex))
                                    ==tri.end()&&
                               std::find(tri.begin(),tri.end(),
                                         static_cast<std::uint32_t>(mate))
                                    ==tri.end())continue;
                            const auto old=cross(
                                current.positions[tri[1]]-current.positions[tri[0]],
                                current.positions[tri[2]]-current.positions[tri[0]]);
                            const auto updated=cross(q-p,r-p);
                            if(length(updated)<=1e-16||dot(old,updated)<=0) {
                                legal=false;break;
                            }
                        }
                        if(!legal)continue;
                        SpatialCapContinuity trialComparison;
                        try {
                            trialComparison=measureSpatialCapContinuity(
                                proposed,survivingFaceNormals,
                                reference,continuityLimits);
                        }catch(const std::exception&) {continue;}
                        const auto candidateScore=score(trialComparison);
                        if(!(candidateScore+1.e-5<bestScore)||
                           trialComparison.maximumBoundaryJumpRadians>
                           comparison.maximumBoundaryJumpRadians+1.e-8)
                            continue;
                        // A smooth edge must not be sacrificed to improve
                        // the 156-degree worst defect on its opposite side.
                        for(std::size_t k=0;k<n;++k) {
                            const auto before=comparison.edges[k]
                                .boundaryNormalJumpRadians;
                            const auto after=trialComparison.edges[k]
                                .boundaryNormalJumpRadians;
                            if(before<.35&&after>.75) {legal=false;break;}
                        }
                        if(!legal)continue;
                        if(budgetPerEmbedding>limits.maxIntersectionTests-tests) {
                            exhausted=true;break;
                        }
                        proposed.minimumQuality=1.;
                        try {
                            if(!embedded(proposed))continue;
                        }catch(const std::length_error&) {
                            exhausted=true;break;
                        }catch(const std::logic_error&) {
                            continue;
                        }
                        if(proposed.minimumQuality+1e-12<
                           limits.desiredMinimumQuality)continue;
                        bestScore=candidateScore;
                        best=std::move(proposed);
                        bestComparison=std::move(trialComparison);
                    }
                }
                if(!(bestScore+1.e-5<currentScore))break;
                current=std::move(best);
                comparison=std::move(bestComparison);
                currentScore=bestScore;
                ++acceptedMoves;
            }
            // Diagnostic-only output on the opt-in path; even if the
            // optimizer finds nothing legal, R06 remains unchanged.
            std::cerr<<"[repair-r06-m18d] trials="<<proposedTrials
                     <<" accepted_rounds="<<acceptedMoves
                     <<" before_score="<<score(measureSpatialCapContinuity(
                         result,survivingFaceNormals,reference,continuityLimits))
                     <<" after_score="<<currentScore
                     <<" before_max_boundary_jump_deg="
                     <<measureSpatialCapRimProfile(result,survivingFaceNormals)
                         .maximumAbsoluteDihedralRadians*(180./std::acos(-1.))
                     <<" after_max_boundary_jump_deg="
                     <<comparison.maximumBoundaryJumpRadians*(180./std::acos(-1.))
                     <<" before_min_q="<<result.minimumQuality
                     <<" after_min_q="<<current.minimumQuality
                     <<" unchanged="<<(acceptedMoves==0)
                     <<" search_budget_exhausted="<<exhausted<<"\n";
            if(acceptedMoves)result=std::move(current);
        }
    }
    if((limits.probeFirstRingFeasibility||limits.stageFirstRingFeasibilityPreview)&&initiallyEmbedded&&
       result.minimumQuality+1e-12>=limits.desiredMinimumQuality&&
       !survivingFaceNormals.empty()) {
        // M19A does NOT alter the resulting cap. This counterfactual
        // probe consumes the very same finite cap-self-contact budget as
        // M17D/M18D/M18E. The full survivor/contact admission still
        // belongs to the downstream PRIVATE staging validator.
        std::vector<SurvivorDirectionalCurvature> untrusted(n);
        const auto& sources=incomingReference?*incomingReference:untrusted;
        SpatialCapFeasibilityLimits probeLimits;
        probeLimits.minimumQuality=limits.desiredMinimumQuality;
        try {
            const auto& mirror=limits.requireMirrorPlane?partner:
                std::vector<std::size_t>{};
            SpatialCapPatch previewCandidate;
            const auto report=probeSpatialCapFirstRingFeasibility(
                result,survivingFaceNormals,sources,mirror,h,
                [&](SpatialCapPatch& candidate){return embedded(candidate);},
                probeLimits,
                limits.stageFirstRingFeasibilityPreview?
                    &previewCandidate:nullptr);
            const auto deg=180./std::acos(-1.);
            std::cerr<<"[repair-r06-m19a-feasibility] candidates="
                     <<report.proposed
                     <<" admissible="<<report.locallyAdmissible
                     <<" accepted_rounds="<<report.acceptedRounds
                     <<" before_max_seam_deg="
                     <<report.baselineWorstSeamRadians*deg
                     <<" best_max_seam_deg="
                     <<report.bestWorstSeamRadians*deg
                     <<" before_max_cap_rim_deg="
                     <<report.baselineWorstCapRimRadians*deg
                     <<" best_max_cap_rim_deg="
                     <<report.bestWorstCapRimRadians*deg
                     <<" before_mean_score="<<report.baselineMeanScore
                     <<" best_mean_score="<<report.bestMeanScore
                     <<" before_min_q="<<report.baselineMinimumQuality
                     <<" best_min_q="<<report.bestMinimumQuality
                     <<" average_normal_initial_offset_over_edge="
                     <<report.averageNormalInitialOffsetOverEdge
                     <<" normal_sweep_max_over_edge="
                     <<report.normalSweepMaxOverEdge
                     <<" inward_proposals="<<report.normalInwardProposals
                     <<" outward_proposals="<<report.normalOutwardProposals
                     <<" inward_admissible="<<report.normalInwardAdmissible
                     <<" outward_admissible="<<report.normalOutwardAdmissible
                     <<" sample_beyond_plane_positive="
                     <<report.sampledPositivePlaneSide
                     <<" sample_beyond_plane_negative="
                     <<report.sampledNegativePlaneSide
                     <<" min_normal_delta_over_edge="
                     <<report.minSampledNormalDeltaOverEdge
                     <<" max_normal_delta_over_edge="
                     <<report.maxSampledNormalDeltaOverEdge
                     <<" positive_sweep_bands="
                     <<report.nearToFarPositiveSamples[0]<<","
                     <<report.nearToFarPositiveSamples[1]<<","
                     <<report.nearToFarPositiveSamples[2]<<","
                     <<report.nearToFarPositiveSamples[3]
                     <<" negative_sweep_bands="
                     <<report.nearToFarNegativeSamples[0]<<","
                     <<report.nearToFarNegativeSamples[1]<<","
                     <<report.nearToFarNegativeSamples[2]<<","
                     <<report.nearToFarNegativeSamples[3]
                     <<" quality_rejected="<<report.qualityRejected
                     <<" orientation_rejected="<<report.orientationRejected
                     <<" score_rejected="<<report.scoreRejected
                     <<" contact_rejected="<<report.contactRejected
                     <<" contact_budget_exhausted="
                     <<report.contactBudgetExhausted
                     <<" unchanged="<<!report.improved
                     <<" note=finite_local_candidates_not_global_proof\n";
            if(limits.stageFirstRingFeasibilityPreview) {
                // This is deliberately restricted by the command-line
                // contract to interactive saved-case STEP DEBUG. Geometry
                // remains PRIVATE and all downstream whole-survivor
                // validation is unchanged; a local cap self-contact pass
                // does NOT certify a full-mesh repair.
                if(report.improved)result=std::move(previewCandidate);
                std::cerr<<"[repair-r06-m19a-provisional-stage]"
                         <<" candidate_applied="<<report.improved
                         <<" changed_positions_only=1"
                         <<" minimum_cap_quality="<<result.minimumQuality
                         <<" whole_mesh_certified=0"
                         <<" publication=disabled\n";
            }
        }catch(const std::exception& error) {
            std::cerr<<"[repair-r06-m19a-feasibility] unavailable="
                     <<error.what()<<"\n";
        }
    }
    if((limits.probeBandDiagonalFeasibility||limits.stageBandDiagonalPreview)&&
       initiallyEmbedded&&
       result.minimumQuality+1e-12>=limits.desiredMinimumQuality&&
       !survivingFaceNormals.empty()&&!result.usedMirroredRibbonFallback) {
        try {
            // Same PRIVATE current cap, same cumulative collision budget;
            // report only. No tested alternate face enters staging.
            const auto& mirror=limits.requireMirrorPlane?partner:
                std::vector<std::size_t>{};
            SpatialCapDiagonalProbeLimits search;
            search.minimumQuality=limits.desiredMinimumQuality;
            SpatialCapPatch previewCandidate;
            const auto report=probeSpatialCapDiagonalFeasibility(
                result,survivingFaceNormals,mirror,
                [&](SpatialCapPatch& candidate){return embedded(candidate);},
                search,
                limits.stageBandDiagonalPreview?&previewCandidate:nullptr);
            const auto deg=180./std::acos(-1.);
            std::cerr<<"[repair-r06-m19c-diagonals] candidates="
                     <<report.candidates
                     <<" admissible="<<report.admissible
                     <<" accepted_rounds="<<report.acceptedRounds
                     <<" before_max_seam_deg="<<report.baselineWorstSeamRadians*deg
                     <<" best_max_seam_deg="<<report.bestWorstSeamRadians*deg
                     <<" before_max_cap_rim_deg="<<report.baselineWorstCapRimRadians*deg
                     <<" best_max_cap_rim_deg="<<report.bestWorstCapRimRadians*deg
                     <<" before_mean_score="<<report.baselineMeanScore
                     <<" best_mean_score="<<report.bestMeanScore
                     <<" before_min_q="<<report.baselineMinimumQuality
                     <<" best_min_q="<<report.bestMinimumQuality
                     <<" quality_rejected="<<report.qualityRejected
                     <<" orientation_rejected="<<report.orientationRejected
                     <<" score_rejected="<<report.scoreRejected
                     <<" contact_rejected="<<report.contactRejected
                     <<" contact_budget_exhausted="<<report.budgetExhausted
                     <<" unchanged="<<!report.improved
                     <<" selected_quad_orbits=";
            for(const auto& orbit:report.acceptedQuadOrbits)
                std::cerr<<orbit[0]<<":"<<orbit[1]<<";";
            std::cerr<<" note=finite_local_flips_not_global_proof\n";
            if(limits.stageBandDiagonalPreview) {
                // Step-debug-only counterfactual. The selected patch has
                // passed cap-local orientation/q/embedding preflight, NOT
                // whole survivor+cap acceptance. The downstream original
                // PRIVATE source-backed closure validator is unchanged.
                if(report.improved)result=std::move(previewCandidate);
                std::cerr<<"[repair-r06-m19d-provisional-stage]"
                         <<" candidate_applied="<<report.improved
                         <<" changed_faces_only=1"
                         <<" minimum_cap_quality="<<result.minimumQuality
                         <<" whole_mesh_certified=0"
                         <<" publication=disabled\n";
            }
        }catch(const std::exception& error) {
            std::cerr<<"[repair-r06-m19c-diagonals] unavailable="
                     <<error.what()<<"\n";
        }
    }
    // M21A: Optional whole-cap fairing runs AFTER the existing M19 previews,
    // but BEFORE any private provisional IDs are committed to the stage.
    // Its failure/no-improvement can NEVER reject a formerly legal cap.
    if(limits.stageWholeCapFairingPreview&&initiallyEmbedded&&
       result.minimumQuality+1e-12>=limits.desiredMinimumQuality&&
       !survivingFaceNormals.empty()&&!result.usedMirroredRibbonFallback) {
        const auto originalAccepted=result; // bit-identical valid fallback
        try {
            SpatialCapFairingLimits search;
            search.minimumQuality=limits.desiredMinimumQuality;
            SpatialCapPatch alternative;
            const auto report=proposeSpatialCapWholeFairing(
                originalAccepted,survivingFaceNormals,
                limits.requireMirrorPlane?partner:std::vector<std::size_t>{},
                h,[&](SpatialCapPatch& candidate){return embedded(candidate);},
                search,&alternative);
            if(report.improved)result=std::move(alternative);
            std::cerr<<"[repair-r06-m21a-fairing]"
                     <<" candidate_applied="<<report.improved
                     <<" trial_count="<<report.trials
                     <<" score_improving_trials="<<report.scoreImprovingTrials
                     <<" legally_admissible_trials="<<report.legallyAdmissibleTrials
                     <<" rounds="<<report.acceptedRounds
                     <<" baseline_score="<<report.baseline.total
                     <<" selected_score="<<report.selected.total
                     <<" baseline_worst_interior_deg="
                     <<report.baseline.worstInteriorRadians*(180./std::acos(-1.))
                     <<" selected_worst_interior_deg="
                     <<report.selected.worstInteriorRadians*(180./std::acos(-1.))
                     <<" baseline_worst_seam_deg="
                     <<report.baseline.worstSeamRadians*(180./std::acos(-1.))
                     <<" selected_worst_seam_deg="
                     <<report.selected.worstSeamRadians*(180./std::acos(-1.))
                     <<" min_q="<<result.minimumQuality
                     <<" budget_exhausted="<<report.contactBudgetExhausted
                     <<" baseline_fallback="<<!report.improved
                     <<" whole_mesh_certified=0 publication=disabled\n";
        }catch(const std::exception& error) {
            result=originalAccepted;
            std::cerr<<"[repair-r06-m21a-fairing] unavailable="<<error.what()
                     <<" baseline_fallback=1 whole_mesh_certified=0"
                     <<" publication=disabled\n";
        }
    }
    if(initiallyEmbedded)return result;
    // Do not raise the 512-split budget or lower q >= .10. Try different
    // reflected TOPOLOGY only after the existing front truly self-intersects.
    // The same cumulative collision-work quota applies to both candidates.
    if(limits.requireMirrorPlane) {
        auto ribbon=mirroredRibbon(orientedCapRim,partner,limits);
        if(embedded(ribbon))return ribbon;
    }
    throw std::logic_error("R06-M06C folded spatial front self-intersects");
}
